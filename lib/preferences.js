const { AD_SELECTORS } = require('./ads');
const { MEDIA_ID } = require('./media');
const { DEFAULT_DOMAIN, normalizeDomain } = require('./navigation');

const defaults = {
  language: 'fr',
  domain: DEFAULT_DOMAIN,
  autoDomain: true,
  blockAds: true,
  websiteTheme: true,
  theme: 'samani',
  colorA: '#ffb45f',
  colorB: '#ff91a8',
  angle: 135,
  background: 'gradient',
  media: null,
  blur: 12,
  brightness: 45,
  surface: 82,
  sidebarCollapsed: false,
  pauseBackground: true,
  reducedMotion: false,
  intro: true,
  alwaysOnTop: false,
  minimizeToTray: false,
  rememberWindow: true,
  startAtLogin: false,
  rpcEnabled: true,
  rpcShowTitle: true,
  rpcShowEpisode: true,
  rpcButtons: true,
};
const presets = {
  samani: { colorA: '#ffb45f', colorB: '#ff91a8', angle: 135 },
  sakura: { colorA: '#fda4af', colorB: '#c084fc', angle: 145 },
  ocean: { colorA: '#38bdf8', colorB: '#818cf8', angle: 120 },
  midnight: { colorA: '#94a3b8', colorB: '#475569', angle: 160 },
};
function sanitize(input = {}, base = defaults) {
  const output = { ...base };
  for (const key of Object.keys(defaults)) {
    const value = input[key];
    if (value === undefined) continue;
    if (typeof defaults[key] === 'boolean' && typeof value === 'boolean') output[key] = value;
  }
  if (['fr', 'en', 'ja'].includes(input.language)) output.language = input.language;
  if (Object.hasOwn(presets, input.theme)) output.theme = input.theme;
  if (['gradient', 'image', 'video', 'solid'].includes(input.background))
    output.background = input.background;
  for (const key of ['colorA', 'colorB'])
    if (/^#[0-9a-f]{6}$/i.test(input[key] || '')) output[key] = input[key];
  for (const [key, min, max] of [
    ['angle', 0, 360],
    ['blur', 0, 40],
    ['brightness', 10, 100],
    ['surface', 35, 100],
  ]) {
    if (typeof input[key] === 'number' && Number.isFinite(input[key]))
      output[key] = Math.round(Math.min(max, Math.max(min, input[key])));
  }
  const domain = normalizeDomain(input.domain);
  if (domain) output.domain = domain;
  // Media IDs are generated by the native file picker, never renderer paths.
  if (input.media === null || MEDIA_ID.test(input.media || '')) output.media = input.media;
  return output;
}
function websiteCss(prefs) {
  const p = sanitize(prefs);
  const opacity = p.surface / 100;
  return `body,input,select,textarea,p,label{font-family:'Segoe UI Variable Text','Segoe UI',system-ui,sans-serif!important}h1,h2,h3,button{font-family:Beckman,'Segoe UI',sans-serif!important;font-weight:700!important}:root{--samani-accent:${p.colorA};--samani-accent-secondary:${p.colorB};color-scheme:dark}${p.websiteTheme ? `html,body{background:transparent!important}body{--bg:transparent;--bg-root:transparent}#main,#contenu,.asn-main,.asn-container{background:transparent!important}.bg-slate-900,.bg-gray-900,.bg-zinc-900,.asn-card,.asn-panel{background:rgba(13,14,20,${opacity})!important}a:hover{color:${p.colorA}!important}.text-cyan-400,.text-sky-400{color:${p.colorA}!important}.border-cyan-500,.border-sky-500{border-color:${p.colorB}!important}` : ''}${p.blockAds ? `${AD_SELECTORS}{display:none!important}` : ''}header.asn-header,footer.asn-footer{background:rgba(13,14,20,${opacity})!important;backdrop-filter:blur(16px)}::selection{background:${p.colorB};color:#111}::-webkit-scrollbar{width:8px}::-webkit-scrollbar-thumb{background:#ffffff28;border-radius:8px}a:focus-visible,button:focus-visible{outline:2px solid ${p.colorA};outline-offset:3px}${p.reducedMotion ? '*,*::before,*::after{scroll-behavior:auto!important;animation-duration:.01ms!important;transition-duration:.01ms!important}' : ''}`;
}
module.exports = { defaults, presets, sanitize, websiteCss };
